"""Единицы OOXML, которые writer пишет в XML сам, мимо свойств python-pptx.

Кегль в `a:rPr/@sz` и `a:endParaRPr/@sz` — целое число сотых пункта. Там, где python-pptx
свойства не даёт (`endParaRPr` пустой ячейки, прогон зоны рецепта), перевод делается
здесь, в одном месте: округление, написанное в двух местах по-разному, дало бы соседним
фигурам одного кегля разный `sz`.
"""

from __future__ import annotations


def size_hundredths(size_pt: float) -> str:
    """Кегль в пунктах → значение атрибута `sz`: сотые пункта, целым числом."""
    return str(round(size_pt * 100))
