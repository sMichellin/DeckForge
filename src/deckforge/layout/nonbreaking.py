"""Неразрывные пробелы: короткое слово не остаётся в конце строки. Change
`no-hanging-prepositions`, Т4 (`docs/agents/requirements-from-notes-26-09.md`).

Заметка 26.09: «…при создании презентаций в / фирменном стиле» — предлог «в» остался
в конце строки. Типографское правило простое: предлог, союз и частица привязываются
к следующему слову, число — к своей единице, группы разрядов числа — друг к другу,
тире — к слову перед ним.

Правило одно на замер (`layout.metrics.split_paragraphs`), pptx (`rendering`) и html
(`export`): замер, который переносит строку не там, где её перенесёт PowerPoint, врёт
о вписывании. IR правило не трогает — текст блока остаётся тем, что написала модель,
неразрывные пробелы появляются только там, где текст меряют и пишут в файл.

Слова правила — свойства языка, а не шаблона (правило 2 AGENTS.md не задето): русские
предлоги и союзы в латинском тексте просто не встречаются, и правило ничего не меняет.
"""

from __future__ import annotations

import re
from typing import Final

NBSP: Final = " "

#: Предлоги, союзы и частицы, которые не остаются в конце строки. Короткие — все:
#: однобуквенные читаются как опечатка на краю строки, двух-трёхбуквенные рвут смысл.
SHORT_WORDS: Final = frozenset(
    {
        # предлоги
        "в", "во", "к", "ко", "с", "со", "у", "о", "об", "обо", "от", "ото", "до", "по",
        "за", "из", "изо", "на", "над", "под", "при", "про", "без", "для", "через", "перед",
        # союзы
        "и", "а", "но", "да", "или", "либо", "что", "как", "чтобы", "если", "ни",
        # частицы, стоящие перед словом
        "не",
    }
)

_WORDS = "|".join(sorted(SHORT_WORDS, key=len, reverse=True))
#: Короткое слово целиком (слева не буква, не цифра и не дефис), за ним обычный пробел
#: и продолжение строки.
_SHORT_BEFORE_WORD: Final = re.compile(rf"(?<![\w-])({_WORDS}) (?=\S)", re.IGNORECASE)

#: Группа разрядов: «1 480» не рвётся на «1» и «480».
_THOUSANDS: Final = re.compile(r"(?<=\d) (?=\d{3}(?!\d))")

#: Число и его единица: «37,5 %», «14 месяцев» — нет, «480 млн», «260 млн ₽» — да.
_UNITS = r"%|‰|₽|\$|€|млн|млрд|трлн|тыс|руб|шт|п\.\s?п\.|pt|см|мм|км|кг|ч|мин|сек|дн"
_NUMBER_UNIT: Final = re.compile(rf"(?<=\d) (?=(?:{_UNITS})(?![\w]))")
#: Множитель и валюта: «млн ₽», «тыс. руб.».
_SCALE_CURRENCY: Final = re.compile(r"(млн|млрд|трлн|тыс\.?) (?=₽|руб|\$|€)")

#: Тире не начинает строку: пробел перед ним неразрывный.
_BEFORE_DASH: Final = re.compile(r" (?=[—–] )")


def bind(text: str) -> str:
    """Текст с неразрывными пробелами там, где перенос строки запрещён.

    Идемпотентна: повторный вызов ничего не меняет. Обычные пробелы между
    самостоятельными словами остаются обычными — переносить строку есть где.
    """
    if not text:
        return text
    text = _SHORT_BEFORE_WORD.sub(lambda match: match.group(1) + NBSP, text)
    text = _THOUSANDS.sub(NBSP, text)
    text = _NUMBER_UNIT.sub(NBSP, text)
    text = _SCALE_CURRENCY.sub(lambda match: match.group(1) + NBSP, text)
    return _BEFORE_DASH.sub(NBSP, text)
